# Minimum cosine score required for a semantic-search hit to surface on the
# browse page. For sentence-transformers/all-MiniLM-L6-v2 on short structured
# material/recipe text, observed scores cluster as:
#   >= 0.70   strong match (synonym / direct term overlap)
#   0.60-0.70 related (same domain, partial overlap)
#   0.50-0.60 weak / thematic noise
#   <  0.50   unrelated
# The default 0.55 trims the worst noise while leaving borderline-related
# hits visible. Lower it if the catalog is small enough that every hit
# matters; raise it as the dataset grows and noise piles up.
