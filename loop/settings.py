# MongoDB Configuration
import mongoengine
from urllib.parse import urlparse, urlunparse

MONGODB_URI = os.environ.get("MONGODB_URI", "mongodb://localhost:27017/loop")
mongoengine.connect(host=MONGODB_URI, tz_aware=True)


def _default_raw_uri(primary_uri: str) -> str:
    """Derive a sensible ``loop_raw`` URI from the primary Mongo URI.

    Keeps host/port/auth identical to the main DB and just swaps the path to
    ``/loop_raw``. This means Docker users only need to set ``MONGODB_URI``
    and the raw connection Just Works against the same Mongo instance.
    """
    parsed = urlparse(primary_uri)
    return urlunparse(parsed._replace(path="/loop_raw"))


# Flat "Raw" database used as a portable file-level backup. Lives under the
# ``raw`` MongoEngine alias; see catalog/raw_db.py. Defaults to the same host
# as ``MONGODB_URI`` so Docker and local dev share a single config knob.
MONGODB_RAW_URI = os.environ.get("MONGODB_RAW_URI", _default_raw_uri(MONGODB_URI))
mongoengine.connect(alias="raw", host=MONGODB_RAW_URI, tz_aware=True)
